export function getTasksForMonth(category, code, monthOffset = 0) {
    let pool = [];
    if (category === 'balanced') {
        pool = [
            ...database.classic,
            ...database.female_lead,
            ...database.kamasutra,
            ...database.bdsm,
            ...database.oral_guide,
            ...database.tantra,
            ...database.locations,
            ...database.roles
        ];
    } else {
        pool = [...(database[category] || database.classic)];
    }

    const targetDate = new Date(currentYear, currentMonth + monthOffset, 1);
    const targetYear = targetDate.getFullYear();
    const targetMonth = targetDate.getMonth();
    const daysInTargetMonth = new Date(targetYear, targetMonth + 1, 0).getDate();

    let seed = 0;
    for (let i = 0; i < code.length; i++) seed += code.charCodeAt(i);
    seed = seed * 31 + targetYear * 12 + targetMonth;

    // Шалфинг Фишера-Йейтса с детерминированным зерном
    const shuffledPool = [...pool];
    for (let i = shuffledPool.length - 1; i > 0; i--) {
        const j = Math.abs((seed * (i + 1) * 17 + i * 3) % (i + 1));
        [shuffledPool[i], shuffledPool[j]] = [shuffledPool[j], shuffledPool[i]];
    }

    // Извлечение только уникальных объектов для дней месяца без повторов
    const usedIds = new Set();
    const uniqueMonthPool = [];
    for (const task of shuffledPool) {
        if (!usedIds.has(task.id)) {
            usedIds.add(task.id);
            uniqueMonthPool.push(task);
        }
        if (uniqueMonthPool.length >= daysInTargetMonth) break;
    }

    // Если уникальных объектов меньше, чем дней (например в маленьких категориях), дополняем с модификаторами
    let poolIdx = 0;
    while (uniqueMonthPool.length < daysInTargetMonth) {
        const baseTask = pool[poolIdx % pool.length];
        const cloneId = `${baseTask.id}_var_${uniqueMonthPool.length}`;
        if (!usedIds.has(cloneId)) {
            usedIds.add(cloneId);
            uniqueMonthPool.push({
                ...baseTask,
                id: cloneId,
                title: `${baseTask.title} (Вариация ${uniqueMonthPool.length + 1})`
            });
        }
        poolIdx++;
    }

    const result = [];
    for (let day = 1; day <= daysInTargetMonth; day++) {
        const goldSecret = goldCardsList.find(g => g.day === day);
        
        if (goldSecret) {
            result.push({
                day: day,
                id: `gold_${day}`,
                title: `${day < 10 ? '0' + day : day}. ${goldSecret.title}`,
                category: "✨ ЗОЛОТАЯ КАРТОЧКА",
                lead: "🎉 СЕКРЕТНЫЙ СЮРПРИЗ",
                roleClass: "role-both",
                img: imgPool[day % imgPool.length],
                task: goldSecret.task,
                tip: goldSecret.tip,
                isGold: true
            });
        } else {
            const base = uniqueMonthPool[(day - 1) % uniqueMonthPool.length];
            
            result.push({
                day: day,
                id: base.id,
                title: `${day < 10 ? '0' + day : day}. ${base.title}`,
                category: base.categoryLabel || 'Практика',
                lead: base.lead,
                roleClass: base.lead.includes("Она — Ведущая") ? "role-f" : (base.lead.includes("Он — Ведущий") ? "role-m" : "role-both"),
                img: imgPool[(day - 1) % imgPool.length],
                task: base.task,
                tip: base.tip,
                isGold: false
            });
        }
    }
    return result;
}
